def revert(ctx, result, level=None, save_dir=None):
    """Remove shadow modules for one level, or all of them (§10.6)."""
    save_dir = save_dir or ctx.save_dir()
    installed = find_installed(save_dir)
    if level is not None:
        installed = [item for item in installed if item.get("level") == int(level)]
    if not installed:
        result.note(
            "no shadow modules installed{0}".format(
                "" if level is None else " for level {0}".format(level)
            )
        )
        return result

    files = [item["path"] for item in installed]
    files += [item["original_copy"] for item in installed if item.get("original_copy") and os.path.exists(item["original_copy"])]
    if not ctx.dry_run:
        manifest = backup.snapshot(
            files,
            label="data-revert",
            command=" ".join(ctx.argv) if ctx.argv else ctx.command,
            version_string=_version_of(ctx),
        )
        result.snapshot = manifest["id"]
        ctx.state.record_snapshot(manifest["id"])
    for item in installed:
        for path in (item["path"], item.get("original_copy")):
            if not path or not os.path.exists(path):
                continue
            result.add_change(_rel(path, save_dir.path), "installed", None)
            if not ctx.dry_run:
                try:
                    os.remove(path)
                except OSError as exc:
                    raise ValidationError("cannot remove {0}: {1}".format(path, exc), path=path)
                _prune_empty_dirs(os.path.dirname(path), save_dir.path)
    if ctx.dry_run:
        result.dry_run = True
        result.note("dry run: nothing was removed")
    _record(ctx, result)
    result.note("shipped values are restored exactly: no game file was ever modified")
    return result


def list_overrides(ctx, save_dir=None, bundle=None):
    """Levels that *can* be overridden, and which overrides are installed."""
    save_dir = save_dir or ctx.save_dir()
    installed = find_installed(save_dir)
    installed_levels = sorted({item["level"] for item in installed if item.get("level")})
    candidates = []
    if bundle is None:
        try:
            bundle = ctx.bundle()
        except KrcheatError:
            bundle = None
    if bundle is not None:
        try:
            archive = mine.Archive(bundle)
            candidates = mine.mine_levels(archive)
        except Exception:
            candidates = []
    if not candidates:
        candidates = list(range(1, 27))
    return {
        "save_dir": save_dir.path,
        "levels": candidates,
        "installed": installed,
        "installed_levels": installed_levels,
    }


def _record(ctx, result):
    """Keep the machine-owned list of F15 files in step with the filesystem."""
    try:
        installed = find_installed(ctx.save_dir())
        ctx.state.put(
            "f15_installed",
            [
                {
                    "level": item.get("level"),
                    "module": item.get("module"),
                    "path": item.get("path"),
                    "fields": item.get("fields"),
                }
                for item in installed
            ],
        )
    except KrcheatError:
        pass


def _version_of(ctx):
    try:
        bundle = ctx.bundle()
        return bundle.expected_version_string()
    except KrcheatError:
        return None


def _rel(path, root):
    try:
        return os.path.relpath(path, root)
    except ValueError:
        return path


def _prune_empty_dirs(directory, stop):
    """Remove the directories we emptied, but never the save directory itself.

    Reverting an override should leave the save directory as it was found: an empty
    `kr1/data/levels/` is inert, but it looks like something was left behind.
    """
    stop = os.path.abspath(stop)
    current = os.path.abspath(directory)
    while current != stop and current.startswith(stop + os.sep):
        try:
            if os.listdir(current):
                return
            os.rmdir(current)
        except OSError:
            return
        current = os.path.dirname(current)
