def render_module(level, target_module, overrides, original_rel, version_string=None):
    """Render the shadow module in the same style the save writer uses."""
    lines = []
    for key, value in overrides.items():
        lines.append('\t{0} = {1};'.format(lt.render_key(key), lt.render_scalar(value).text))
    body = "\n".join(lines)
    return MODULE_TEMPLATE.format(
        mheader=MARKER,
        level=int(level),
        generated=datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        version=version_string or "unknown",
        target=target_module,
        table=body + "\n" if body else "",
        original=original_rel,
    )


def expand_fields(field, value):
    """Map a documented field name onto the names the shipped code may use."""
    if field in FIELD_ALIASES:
        return {name: value for name in FIELD_ALIASES[field]}
    return {field: value}


def _extract_original(ctx, save_dir, module_name, result):
    """Copy the shipped module out of `game.love` so the shadow can call it."""
    archive = mine.Archive(ctx.bundle())
    if not archive.has(module_name):
        raise NotFoundError(
            "{0} is not in the archive; this level has no data module to override".format(
                module_name
            ),
            module=module_name,
        )
    data = archive.read(module_name)
    if not data:
        raise ValidationError("could not read {0} from the archive".format(module_name))
    if not data.startswith(b"\x1bLJ"):
        result.warn(
            "{0} is not LuaJIT bytecode (unexpected), it is copied as-is".format(module_name)
        )
    destination = original_path(save_dir, module_name)
    os.makedirs(os.path.dirname(destination), exist_ok=True)
    with open(destination, "wb") as handle:
        handle.write(data)
    ctx.log_info(
        "data.original_extracted",
        module=module_name,
        bytes=len(data),
        destination=destination,
    )
    return destination, data


def set_level_data(ctx, result, level, field, value, save_dir=None):
    """Generate or extend the shadow module for one level (§10.6)."""
    level = int(level)
    if level <= 0:
        raise UsageError("--level must be positive")
    value = int(value)
    if field not in FIELD_ALIASES and field not in ("initial_gold", "initial_lives",
                                                    "starting_gold", "starting_lives"):
        raise UsageError(
            "unknown level field {0!r}; expected starting_gold or starting_lives".format(field)
        )
    save_dir = save_dir or ctx.save_dir()
    module_name = level_module_name(level)
    target = shadow_path(save_dir, module_name)

    existing = read_installed(target, save_dir) if os.path.exists(target) else {"fields": {}}
    previous = dict(existing.get("fields") or {})
    overrides = dict(previous)
    overrides.update(expand_fields(field, value))
    for key in sorted(overrides):
        result.add_change(
            "{0}.{1}".format(module_name, key),
            previous.get(key),
            overrides[key],
        )

    original_rel = os.path.relpath(original_path(save_dir, module_name), save_dir.path)
    text = render_module(level, module_name, overrides, original_rel, _version_of(ctx))
    if len(text) > MAX_MODULE_BYTES:
        raise ValidationError("generated module exceeds {0} bytes".format(MAX_MODULE_BYTES))

    # Compile it in the game's own VM before it is installed (S8, D4). `run` mode is not
    # used: the module calls into LÖVE, which does not exist outside the game.
    from krcheat.core import safety as safety_mod

    if ctx.oracle:
        safety_mod.oracle_check(ctx, text, module_name, run=False)

    if ctx.dry_run:
        result.dry_run = True
        result.note("dry run: nothing was written")
        result.set(module=module_name, shadow=str(target), overrides=overrides)
        return result

    # Snapshot whatever exists. Adding a file is reversible by deleting it, so a
    # fresh install has nothing to preserve; overwriting an existing shadow does.
    files = [path for path in (target, original_path(save_dir, module_name)) if os.path.exists(path)]
    if files:
        manifest = backup.snapshot(
            files,
            label="data-set-level{0}".format(level),
            command=" ".join(ctx.argv) if ctx.argv else ctx.command,
            version_string=_version_of(ctx),
        )
        result.snapshot = manifest["id"]
        ctx.state.record_snapshot(manifest["id"])
        ctx.log_info("data.snapshot", snapshot=manifest["id"], files=len(files))
    else:
        result.note("no snapshot taken: neither the shadow nor its bytecode copy existed yet")

    _extract_original(ctx, save_dir, module_name, result)
    tmp = target + ".tmp"
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, target)
    ctx.log_info(
        "data.installed",
        module=module_name,
        shadow=target,
        bytes=len(text),
        overrides=overrides,
        sha256=paths.sha256_file(target),
    )
    result.set(module=module_name, shadow=str(target), overrides=overrides)
    result.note(
        "F15 requires spike S2 (save-directory require precedence). If S2 has not passed, this "
        "file is inert and the game ignores it."
    )
    if str(field).startswith("starting_"):
        result.note(
            "the level-data field name is unverified: both spellings suggested by the shipped "
            "code were written ({0})".format(", ".join(sorted(expand_fields(field, value))))
        )
    _record(ctx, result)
    return result


