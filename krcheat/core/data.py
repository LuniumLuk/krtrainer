"""F15 — persistent per-level data as *shadow data modules* (§9.8).

The idea, and its dependency
----------------------------
LÖVE mounts the save directory **over** the game source, so a Lua source file placed
in the save directory shadows the same-pathed module inside `game.love`. That is spike
S2, and everything here is conditional on it: **if S2 fails, this module's effect is
inert** and F15 moves to tier 3 (bytecode patching).

Generation, not surgery
-----------------------
Where S2 holds, a persistent "this level starts with 9999 gold" needs no ZIP repack, no
in-place bytecode edit and no re-signing. It needs one generated file per level:

    <save dir>/kr1/data/levels/level01_data.lua     <- shadows the game's bytecode module

The generated module must be **additive**: it loads the shipped module (a bytecode copy
kept alongside, which we load with `love.filesystem.load`) and overrides only the fields
it targets. A game update therefore does not silently inherit stale values, and
`data revert` deletes two files and restores the shipped behaviour exactly.

Field names are unverified
--------------------------
Which keys a level-data table uses for starting gold and lives is *not* measured.
`all/systems.lua` carries `initial_gold` / `initial_lives` (§4.4) while the CLI surface
is specified with `starting_gold` / `starting_lives` (§10.6). Rather than guess, both
spellings are written: the extra key is inert if the game does not read it, and one of
them is right. This is reported as a note on every run, and the real answer comes from
spike S2 followed by `probe`.
"""

from __future__ import annotations

import datetime
import os
import re
from typing import Any, Dict, List, Optional

from krcheat.core import backup, lua_table as lt, mine, paths
from krcheat.core.errors import KrcheatError, NotFoundError, UsageError, ValidationError, milestone

#: Marks a file as ours, so `data revert --all` can find them without any state.
MARKER = "-- krcheat-f15"

#: Directive size cap. A shadow module is a few lines; anything larger is a bug.
MAX_MODULE_BYTES = 64 * 1024

#: `starting_gold` is the documented CLI name; `initial_gold` is what the shipped
#: constants suggest. Both are written (see the module docstring).
FIELD_ALIASES = {
    "starting_gold": ("initial_gold", "starting_gold"),
    "starting_lives": ("initial_lives", "starting_lives"),
    "gold": ("initial_gold", "starting_gold"),
    "lives": ("initial_lives", "starting_lives"),
}

WAVE_FIELD_ALIASES = {
    "gold": ("wave_gold", "gold"),
}

_OVERRIDES_BLOCK = re.compile(r"local OVERRIDES = (\{.*?\n\})", re.S)
_LEVEL_FIELD = re.compile(r"^-- krcheat-f15 level=(\d+)", re.M)

MODULE_TEMPLATE = """\
{mheader} level={level} generated={generated} version={version}
-- Generated by krcheat from the foundation document, section 9.8 (F15).
-- Do not edit: this file is regenerated whole. Remove it with 'krcheat data revert'.
--
-- It shadows {target} inside game.love and overrides only the fields
-- listed below. Requires spike S2 (save-directory require precedence) to have passed.
local OVERRIDES = {{
{table}}}
local base = {{}}
do
\tlocal loader = love and love.filesystem and love.filesystem.load
\tlocal chunk = loader and loader({original!r})
\tif chunk then
\t\tlocal ok, result = pcall(chunk)
\t\tif ok and type(result) == "table" then
\t\t\tbase = result
\t\tend
\tend
end
for key, value in pairs(OVERRIDES) do
\tbase[key] = value
end
return base
"""


def level_module_name(level):
    return "kr1/data/levels/level{0:02d}_data.lua".format(int(level))


def wave_module_name(level, mode):
    return "kr1/data/waves/level{0:02d}_waves_{1}.lua".format(int(level), mode)


def shadow_path(save_dir, module_name):
    return os.path.join(save_dir.path, *module_name.split("/"))


def original_path(save_dir, module_name):
    """Where the shipped bytecode copy lives, inside the save directory.

    It has to live under the save directory because that is the only place
    `love.filesystem.load` can reach without a `require` that would resolve back to
    the shadow itself.
    """
    return os.path.join(save_dir.path, "krcheat", "orig", module_name.replace("/", "__") + ".luac")


#: Where a shadow module can legitimately live. Discovery is deliberately confined to
#: these two directories rather than walking the whole save directory: a walk would also
#: find the *snapshot copies* under `~/.krcheat/backups` when the two trees overlap, and
#: report a reverted override as still installed.
SHADOW_DIRS = ("kr1/data/levels", "kr1/data/waves")


def _shadow_directories(save_dir):
    return [os.path.join(save_dir.path, *relative.split("/")) for relative in SHADOW_DIRS]


def find_installed(save_dir):
    """Every shadow module we installed, discovered by content, not by state."""
    found = []
    for directory in _shadow_directories(save_dir):
        try:
            names = sorted(os.listdir(directory))
        except OSError:
            continue
        for name in names:
            if not name.endswith(".lua"):
                continue
            full = os.path.join(directory, name)
            try:
                with open(full, "r", encoding="utf-8", errors="replace") as handle:
                    head = handle.read(4096)
            except OSError:
                continue
            if head.startswith(MARKER):
                found.append(read_installed(full, save_dir))
    found.sort(key=lambda item: (item.get("level") or 0, item.get("module") or ""))
    return found


def read_installed(path, save_dir=None):
    """Describe one installed shadow module by reading it back."""
    record = {"path": path, "module": None, "level": None, "fields": {}, "installed": None}
    try:
        with open(path, "r", encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return record
    match = _LEVEL_FIELD.search(text)
    if match:
        record["level"] = int(match.group(1))
    first = text.splitlines()[0] if text else ""
    stamp = re.search(r"generated=([0-9T:+.-]+)", first)
    if stamp:
        record["installed"] = stamp.group(1)
    module = re.search(r"-- It shadows (\S+) inside game.love", text)
    if module:
        record["module"] = module.group(1)
    block = _OVERRIDES_BLOCK.search(text)
    if block:
        try:
            table = lt.parse("local obj1 = {0}\nreturn obj1\n".format(block.group(1)))
            record["fields"] = table.python()
        except lt.LuaTableError:
            record["fields"] = {}
    if save_dir is not None and record["module"]:
        record["original_copy"] = original_path(save_dir, record["module"])
    return record


